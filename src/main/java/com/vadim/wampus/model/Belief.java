package com.vadim.wampus.model;

/** Что агент знает о наличии объекта (яма, Вампус, золото) в конкретной комнате. */
public enum Belief {
    /** Ничего не известно. */
    UNKNOWN,
    /** Объекта точно нет. */
    ABSENT,
    /** Объект может быть здесь (P?, W?, G?). */
    POSSIBLE,
    /** Объект точно здесь (P!, W!, G!). */
    PRESENT
}
